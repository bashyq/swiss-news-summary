/// Znuni design system color palette — warm editorial tones with Light/Dark support via Asset Catalog.
/// Core tokens (znNavy, znTerracotta, znCream, znSurface, znBorder, znInk, znBody, znMuted,
/// znPositive, znNegative, znAlertBg, znInnerDivider, znNeutralTagBg, znNeutralTagText, znChevron)
/// are auto-generated by Xcode from the Asset Catalog color sets.
extension Color {
    // MARK: - Legacy Aliases (preserve .brand API across ~87 references)

    static var brand: Color { .znNavy }
    static var brandDark: Color { .znNavy }
    static var brandWarm: Color { .znTerracotta }
    static var appPrimary: Color { .znNavy }
    static var appAccent: Color { .znNavy }
    static var baseline: Color { .znNavy }

    // MARK: - Google Stars (amber #f59e0b)
    static let googleStars = Color(red: 0.961, green: 0.620, blue: 0.043)

    // MARK: - Semantic Colors

    static let positive = Color.znPositive
    static let negative = Color.znNegative
    static let amber = Color.znTerracotta
    static let weatherCard = Color.znNavy.opacity(0.06)

    // MARK: - Badge Colors

    static func badgeColor(for type: String) -> Color {
        switch type {
        case "green": return .znPositive
        case "red": return .znNegative
        case "blue": return .znNavy
        case "amber", "orange": return .znTerracotta
        case "yellow": return .znTerracotta.opacity(0.85)
        case "purple": return .znNavy.opacity(0.75)
        case "gray": return .znMuted
        default: return .znMuted
        }
    }

    // MARK: - Transport Status

    static func transportStatus(_ status: String) -> Color {
        switch status {
        case "none": return .znPositive
        case "minor": return .znTerracotta
        case "major": return .znNegative
        default: return .znMuted
        }
    }

    // MARK: - Sunshine Colors

    static func sunshineColor(hours: Double) -> Color {
        if hours > 6 { return .znTerracotta }
        if hours > 3 { return .znNavy.opacity(0.7) }
        return .znMuted
    }

    // MARK: - Snow Colors

    static func snowColor(cm: Double) -> Color {
        if cm > 30 { return .znNavy }
        if cm > 10 { return .znNavy.opacity(0.6) }
        return .znMuted
    }

    // MARK: - Sentiment

    static func sentimentColor(_ sentiment: String?) -> Color {
        switch sentiment {
        case "positive": return .znPositive
        case "negative": return .znNegative
        default: return .znMuted
        }
    }

    // MARK: - Category Colors

    static func categoryColor(_ key: String) -> Color {
        switch key {
        case "topStories": return .znNavy
        case "politics": return .znNavy.opacity(0.75)
        case "disruptions": return .znNegative
        case "events": return .znPositive
        case "culture": return .znTerracotta
        case "local": return .znTerracotta.opacity(0.7)
        default: return .znMuted
        }
    }

    // MARK: - Card Border Colors

    static func activityBorderColor(indoor: Bool, isFree: Bool) -> Color {
        if isFree { return .znPositive }
        return indoor ? .znNavy : .znTerracotta
    }

    static func cuisineBorderColor(_ category: String?) -> Color {
        switch category?.lowercased() {
        case "swiss": return .znNegative
        case "italian": return .znPositive
        case "asian": return .znTerracotta
        case "kebab": return .znTerracotta.opacity(0.7)
        case "cafe": return .znNavy.opacity(0.65)
        case "vegetarian": return .znPositive.opacity(0.8)
        case "fastfood": return .znTerracotta.opacity(0.85)
        default: return .znNavy
        }
    }
}

