// MARK: - Shadow Tokens

/// Znuni shadow presets for visual hierarchy.
enum AppShadow {
    /// Primary card shadow
    static let card: (color: Color, radius: CGFloat, x: CGFloat, y: CGFloat) = (
        .black.opacity(0.08), 8, 0, 2
    )
    /// Subtle shadow — secondary/lightweight cards
    static let subtle: (color: Color, radius: CGFloat, x: CGFloat, y: CGFloat) = (
        .black.opacity(0.05), 4, 0, 2
    )
}

